"""Verify provider selection through Codex's effective configuration API."""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from codex_mgr.core.profiles import ConfigurationError, parse_configuration
from codex_mgr.core.rpc import CodexReader, CodexRpcError
from codex_mgr.utils.paths import get_config_toml_path


class NativeConfigurationReadError(ConfigurationError):
    """Codex could not read the current file/policy; selection checks did not run."""


@dataclass(frozen=True)
class NativeConfiguration:
    # Effective settings, origins and requirements may contain secrets or paths.
    config: dict = field(repr=False)
    origins: dict = field(repr=False)
    requirements: dict = field(repr=False)


def read_native_configuration(*, cwd: Path | None = None) -> NativeConfiguration:
    """Read policy and layers without sending an inference request or CLI secrets."""
    try:
        with CodexReader() as reader:
            result = reader.request(
                "config/read", {"includeLayers": True, "cwd": str((cwd or Path.cwd()).resolve())}
            )
            policy = reader.request("configRequirements/read")
        config, origins = result.get("config"), result.get("origins")
        if "requirements" not in policy:
            raise ValueError
        requirements = policy["requirements"]
        if requirements is None:
            requirements = {}
        if not all(isinstance(value, dict) for value in (config, origins, requirements)):
            raise ValueError
        return NativeConfiguration(config, origins, requirements)
    except (CodexRpcError, OSError, ValueError, TypeError) as exc:
        raise NativeConfigurationReadError(
            "Codex could not verify effective configuration. Check its installation, "
            "configuration and managed policy before retrying."
        ) from exc


def _get(data, keys):
    for key in keys:
        if not isinstance(data, dict):
            return None
        data = data.get(key)
    return data


def _selection(encoded: bytes) -> dict[tuple[str, ...], object]:
    data = parse_configuration(encoded).unwrap()
    if {"openai", "ollama", "lmstudio"}.intersection(data.get("model_providers", {})):
        raise ConfigurationError(
            "Codex reserves built-in provider IDs. Explicitly rename custom definitions "
            "and their model_provider selection before activation or restore."
        )
    if data.get("profile") is not None or data.get("profiles"):
        raise ConfigurationError(
            "Legacy Codex profiles need explicit migration to named .config.toml files. "
            "Existing profile files were preserved."
        )
    # Omitted controls mean inherit Codex's effective value, not require null.
    values = {
        (key,): data[key]
        for key in ("model", "model_reasoning_effort", "model_context_window")
        if key in data
    }
    selected = data.get("model_provider") or "openai"
    values[("model_provider",)] = selected
    table = data.get("model_providers", {}).get(selected, {})
    if selected != "openai" and not isinstance(table, dict):
        raise ConfigurationError("The selected connection definition is invalid.")
    for key in (
        "name",
        "base_url",
        "wire_api",
        "requires_openai_auth",
        "env_key",
        "experimental_bearer_token",
        "http_headers",
        "env_http_headers",
        "auth",
        "gateway_oauth",
        "aws",
        "query_params",
    ):
        # Built-in OpenAI defaults are owned by Codex, not generated by cmgr.
        if selected == "openai" and key not in table:
            continue
        values[("model_providers", selected, key)] = table.get(key)
    return values


def _origin(snapshot: NativeConfiguration, keys: tuple[str, ...]):
    for length in range(len(keys), 0, -1):
        origin = snapshot.origins.get(".".join(keys[:length]))
        if origin is not None:
            if not isinstance(origin, dict) or not isinstance(origin.get("name"), dict):
                raise ConfigurationError("Codex returned an invalid configuration origin.")
            return origin["name"]
    return None


def validate_activation_configuration(encoded: bytes) -> None:
    """Check selection structure before any repair write or native inspection."""
    _selection(encoded)


def _user_can_replace(origin: dict | None) -> bool:
    if origin is None:
        return True  # Built-in values have no file origin.
    kind = origin.get("type")
    if kind in {"system", "cloud"}:
        return True
    if kind != "user" or origin.get("profile") is not None:
        return False
    try:
        return Path(origin["file"]).resolve() == get_config_toml_path().resolve()
    except (KeyError, TypeError, OSError):
        return False


def _check_policy(snapshot: NativeConfiguration, values: dict) -> None:
    selected = values[("model_provider",)]
    required = snapshot.requirements.get("modelProvider")
    if required is not None and required != selected:
        raise ConfigurationError("Managed policy requires a different Codex connection.")
    definitions = snapshot.requirements.get("modelProviders")
    if definitions is not None:
        if not isinstance(definitions, dict):
            raise ConfigurationError("Codex returned invalid managed provider requirements.")
        for keys, wanted in values.items():
            if keys[0] != "model_providers":
                continue
            actual = _get(definitions, keys[1:])
            if actual != wanted:
                raise ConfigurationError(
                    "Managed policy requires a different provider definition. "
                    "The existing configuration was preserved."
                )
    login = snapshot.requirements.get("allowedLoginMethods")
    method = "chatgpt" if selected == "openai" else "api"
    forced = snapshot.config.get("forced_login_method")
    if forced is not None and forced != method:
        raise ConfigurationError("Effective Codex configuration requires another login method.")
    if login is not None and (not isinstance(login, list) or method not in login):
        raise ConfigurationError("Managed policy does not permit this login method.")


def verify_before_activation(encoded: bytes, *, cwd: Path | None = None) -> None:
    """Reject known layer/policy conflicts before snapshots or configuration writes."""
    values = _selection(encoded)
    snapshot = read_native_configuration(cwd=cwd)
    _check_policy(snapshot, values)
    for keys, wanted in values.items():
        actual = _get(snapshot.config, keys)
        if keys == ("model_provider",):
            actual = actual or "openai"
        if actual != wanted and not _user_can_replace(_origin(snapshot, keys)):
            raise ConfigurationError(
                "Another Codex configuration layer overrides the requested connection or model. "
                "Inspect Codex /debug-config in this working directory before retrying."
            )


def verify_after_activation(encoded: bytes, *, cwd: Path | None = None) -> None:
    """Do not commit manager state unless the effective selection matches the write."""
    values = _selection(encoded)
    snapshot = read_native_configuration(cwd=cwd)
    _check_policy(snapshot, values)
    for keys, wanted in values.items():
        actual = _get(snapshot.config, keys)
        if keys == ("model_provider",):
            actual = actual or "openai"
        if actual != wanted:
            raise ConfigurationError(
                "Codex did not accept the requested connection, model or controls. "
                "Activation was stopped; check managed and project configuration."
            )
